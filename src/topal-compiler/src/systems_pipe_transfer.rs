    e.rr(0x39, R9, A);
    e.0.jump_if(0x86, "pipe-write-count-ready");
    e.mov(R9, A);
    e.0.bind("pipe-write-count-ready")?;
    e.0.call("runtime-readable-extent");
    e.0.jump_if(0x82, "pipe-efault");
    buffer(&mut e, R13);
    e.load(R15, R13, 32);
    e.load(A, R13, 40);
    e.rr(0x01, R15, A);
    e.arith(4, R15, 4095);
    e.mov(Si, R8);
    e.mov(C, R9);
    e.0.bind("pipe-write-byte")?;
    e.mov(Di, R11);
    e.rr(0x01, Di, R15);
    e.0.bytes(&[0x8a, 0x06, 0x88, 0x07, 0x38, 0x07]);
    e.0.jump_if(0x85, "fatal");
    e.add(Si, 1);
    e.add(R15, 1);
    e.arith(4, R15, 4095);
    e.add(C, -1);
    e.cmp(C, 0);
    e.0.jump_if(0x85, "pipe-write-byte");
    e.load(A, R13, 40);
    e.rr(0x01, A, R9);
    e.store(R13, 40, A);
    e.store(R13, 80, Bp);
    e.store(R13, 88, Bp);
    e.0.call("pipe-notify");
    e.mov(A, R9);
    emit_static_process_sysret(e.0);
    e.0.bind("pipe-transfer-zero")?;
    e.imm(A, 0);
    emit_static_process_sysret(e.0);
