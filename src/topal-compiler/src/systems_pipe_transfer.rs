    emit_static_process_sysret(e.0);

    e.0.bind("pipe-write")?;
    e.0.call("pipe-object-lookup");
    e.mov(R13, R10);
    range(&mut e);
    e.cmp(R9, 0);
    e.0.jump_if(0x84, "pipe-transfer-zero");
    e.load(A, R13, 16);
    e.cmp(A, 0);
    e.0.jump_if(0x84, "pipe-write-no-reader");
    e.imm(A, 4096);
    e.load(R11, R13, 40);
    e.rr(0x29, A, R11);
    e.cmp(R9, 4096);
    e.0.jump_if(0x87, "pipe-write-large");
    e.rr(0x39, A, R9);
    e.0.jump_if(0x83, "pipe-write-ready");
    e.0.jump("pipe-write-wait");
    e.0.bind("pipe-write-large")?;
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-write-ready");
    e.0.bind("pipe-write-wait")?;
    e.load(A, R14, 16);
    e.arith(4, A, 0x800);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-eagain");
    e.imm(R8, 1);
    e.imm(R9, 3);
    e.0.jump("pipe-block");
    e.0.bind("pipe-write-no-reader")?;
