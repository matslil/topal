    e.imm(R9, 2);
    e.0.jump("pipe-block");
    e.0.bind("pipe-read-ready")?;
    e.0.call("realtime-observe");
    e.0.jump_if(0x82, "pipe-eio");
    e.mov(Bp, R15);
    resolve(&mut e, 5)?;
    e.gs(0x8b, R8, 320);
    e.gs(0x8b, R9, 328);
    e.load(A, R13, 40);
    e.rr(0x39, R9, A);
    e.0.jump_if(0x86, "pipe-read-count-ready");
