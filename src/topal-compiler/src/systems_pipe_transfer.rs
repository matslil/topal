    buffer(&mut e, R13);
    e.load(R15, R13, 32);
    e.mov(Di, R8);
    e.mov(C, R9);
    e.0.bind("pipe-read-byte")?;
    e.mov(Si, R11);
    e.rr(0x01, Si, R15);
    e.0.bytes(&[0x8a, 0x06, 0x88, 0x07, 0x38, 0x07]);
    e.0.jump_if(0x85, "fatal");
    e.0.bytes(&[0xc6, 0x06, 0, 0x80, 0x3e, 0]);
    e.0.jump_if(0x85, "fatal");
    e.add(Di, 1);
    e.add(R15, 1);
    e.arith(4, R15, 4095);
    e.add(C, -1);
    e.cmp(C, 0);
    e.0.jump_if(0x85, "pipe-read-byte");
    e.store(R13, 32, R15);
    e.load(A, R13, 40);
    e.rr(0x29, A, R9);
    e.store(R13, 40, A);
    e.store(R13, 72, Bp);
    e.0.call("pipe-notify");
