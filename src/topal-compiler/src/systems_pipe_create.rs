use super::*;

pub(super) fn emit(code: &mut X86FunctionEncoder) -> Result<(), CompileError> {
    let mut e = E(code);
    e.0.bind("pipe-create")?;
    e.gs(0x8b, R12, TABLE_CONTEXT);
    e.imm(B, 0);
    e.0.jump("pipe-create-flags-ready");
    e.0.bind("pipe-create2")?;
    e.gs(0x8b, R12, TABLE_CONTEXT);
    e.0.bytes(&[0x89, 0xf6]);
    e.mov(B, Si);
    e.mov(A, B);
    e.arith(4, A, !0x84880);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-einval");
    e.mov(A, B);
    e.arith(4, A, 0x4080);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-enosys");
    e.0.bind("pipe-create-flags-ready")?;
    e.0.bytes(&[0x53]);
    e.0.call("realtime-observe");
    e.0.bytes(&[0x5b]);
    e.0.jump_if(0x82, "pipe-eio");
    e.mov(super::super::R::_Bp, R15);
    e.mov(R13, R12);
    e.add(R13, BASE);
    e.imm(C, 4);
    e.0.bind("pipe-free-object")?;
    e.load(A, R13, 0);
    e.cmp(A, 0);
    e.0.jump_if(0x84, "pipe-free-object-ready");
    e.add(R13, RECORD);
    e.add(C, -1);
    e.cmp(C, 0);
    e.0.jump_if(0x85, "pipe-free-object");
    e.0.jump("pipe-enfile");
    e.0.bind("pipe-free-object-ready")?;
    e.mov(Di, R13);
    e.imm(A, 0);
    e.imm(C, RECORD as u64 / 8);
    e.0.bytes(&[0xfc, 0xf3, 0x48, 0xaf]);
    e.0.jump_if(0x85, "fatal");
    buffer(&mut e, R13);
    e.mov(Di, R11);
    e.imm(C, 512);
    e.0.bytes(&[0xf3, 0x48, 0xaf]);
    e.0.jump_if(0x85, "fatal");
    e.store(R12, STAGING, R13);
    e.load(R15, R12, COUNTER);
    e.add(R15, 1);
    e.0.jump_if(0x82, "pipe-enfile");
    e.imm(R8, 0);
    e.imm(R9, 0);
    e.mov(R13, R12);
    e.add(R13, 64);
    e.0.bind("pipe-free-slot")?;
    e.load(A, R13, 0);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-slot-advance");
    e.mov(Di, R8);
    e.0.bytes(&[0x48, 0xc1, 0xe7, 3]);
    e.rr(0x01, Di, R12);
    e.store(Di, STAGING + 8, R9);
    e.add(R8, 1);
    e.cmp(R8, 2);
    e.0.jump_if(0x84, "pipe-slots-ready");
    e.0.bind("pipe-slot-advance")?;
    e.add(R9, 1);
    e.cmp(R9, 16);
    e.0.jump_if(0x83, "pipe-emfile");
    e.add(R13, 16);
    e.0.jump("pipe-free-slot");
    e.0.bind("pipe-slots-ready")?;
    e.imm(R8, 0);
    e.imm(R9, 1);
    e.mov(R13, R12);
    e.add(R13, DESCRIPTIONS);
    e.0.bind("pipe-free-description")?;
    e.load(A, R13, 0);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-description-advance");
    e.mov(Di, R13);
    e.imm(C, 8);
    e.0.bytes(&[0xfc, 0xf3, 0x48, 0xaf]);
    e.0.jump_if(0x85, "fatal");
    e.mov(Di, R8);
    e.0.bytes(&[0x48, 0xc1, 0xe7, 3]);
    e.rr(0x01, Di, R12);
    e.store(Di, STAGING + 24, R9);
    e.add(R8, 1);
    e.cmp(R8, 2);
    e.0.jump_if(0x84, "pipe-descriptions-ready");
    e.0.bind("pipe-description-advance")?;
    e.add(R9, 1);
    e.cmp(R9, 32);
    e.0.jump_if(0x87, "fatal");
    e.add(R13, 64);
    e.cmp(R9, 17);
    e.0.jump_if(0x85, "pipe-free-description");
    e.mov(R13, R12);
    e.add(R13, CHILD_DESCRIPTIONS);
    e.0.jump("pipe-free-description");
    e.0.bind("pipe-descriptions-ready")?;
    e.gs(0x8b, R8, 312);
    e.imm(R9, 8);
    e.0.call("runtime-writable-extent");
    e.0.jump_if(0x82, "pipe-efault");
    e.load(R13, R12, STAGING);
    e.store(R13, 8, R15);
    for index in 0..2 {
        e.load(R11, R12, STAGING + 24 + index * 8);
        e.store(R13, 16 + index * 8, R11);
        e.mov(R14, R12);
        e.add(R14, DESCRIPTIONS);
        e.cmp(R11, 16);
        let primary = if index == 0 {
            "pipe-read-description-base"
        } else {
            "pipe-write-description-base"
        };
        e.0.jump_if(0x86, primary);
        e.add(R14, CHILD_DESCRIPTIONS - DESCRIPTIONS - 16 * 64);
        e.0.bind(primary)?;
        e.mov(A, R11);
        e.add(A, -1);
        e.0.bytes(&[0x48, 0xc1, 0xe0, 6]);
        e.rr(0x01, R14, A);
        e.imm(A, 5 + index as u64);
        e.store(R14, 0, A);
        e.imm(A, 1);
        e.store(R14, 8, A);
        e.mov(A, B);
        e.arith(4, A, 0x800);
        e.arith(1, A, index);
        e.store(R14, 16, A);
        e.store(R14, 32, R15);
        e.load(A, R12, STAGING + 8 + index * 8);
        e.0.bytes(&[0x48, 0xc1, 0xe0, 4]);
        e.rr(0x01, A, R12);
        e.add(A, 64);
        e.store(A, 0, R11);
        e.mov(C, B);
        e.0.bytes(&[0x48, 0xc1, 0xe9, 19]);
        e.arith(4, C, 1);
        e.store(A, 8, C);
    }
    for offset in [64, 72, 80, 88] {
        e.store(R13, offset, super::super::R::_Bp);
    }
    e.imm(A, 1);
    e.store(R13, 0, A);
    e.store(R12, COUNTER, R15);
    e.load(A, R12, STAGING + 8);
    e.load(C, R12, STAGING + 16);
    e.0.bytes(&[0x48, 0xc1, 0xe1, 32]);
    e.rr(0x09, A, C);
    e.store(R8, 0, A);
    e.load(R11, R8, 0);
    e.rr(0x39, A, R11);
    e.0.jump_if(0x85, "fatal");
    wipe_staging(&mut e);
    e.imm(A, 0);
    emit_static_process_sysret(e.0);
    Ok(())
}
