fn emit_fixture_command_check(code: &mut Vec<u8>, expected: &[u8], legacy: bool, trailing: bool) {
    const BUFFER: u32 = 0x5f8f60;
    for (index, chunk) in expected.chunks(8).enumerate() {
        let address = BUFFER + (index * 8) as u32;
        if legacy || chunk.len() == 8 {
            let mut padded = [0_u8; 8];
            padded[..chunk.len()].copy_from_slice(chunk);
            code.extend_from_slice(&[0x48, 0xb8]);
            code.extend_from_slice(&padded);
            code.extend_from_slice(&[0x48, 0x39, 0x04, 0x25]);
            code.extend_from_slice(&address.to_le_bytes());
            code.extend_from_slice(&[0x75, 0xfe]);
        } else {
            // Read only the delivered suffix; bytes beyond it remain the
            // application's previous data in the owned transfer profile.
            for (offset, byte) in chunk.iter().enumerate() {
                code.extend_from_slice(&[0x80, 0x3c, 0x25]);
                code.extend_from_slice(&(address + offset as u32).to_le_bytes());
                code.extend_from_slice(&[*byte, 0x75, 0xfe]);
            }
        }
    }
    if legacy && trailing {
        let address = BUFFER + expected.len().next_multiple_of(8) as u32;
        code.extend_from_slice(&[0x48, 0x83, 0x3c, 0x25]);
        code.extend_from_slice(&address.to_le_bytes());
        code.extend_from_slice(&[0, 0x75, 0xfe]);
    }
}
