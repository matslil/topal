//! Exact FIFO-generation readiness, distinct from a parent's child-exit wait.
use super::*;

pub(super) fn emit(code: &mut X86FunctionEncoder) -> Result<(), CompileError> {
    let mut e = E(code);
    // R13: owned FIFO. Preserve description/slot/alias/transfer registers.
    e.0.bind("pipe-notify")?;
    e.load(A, R12, HEADER);
    e.cmp(A, 1);
    e.0.jump_if(0x85, "pipe-notify-return");
    e.load(A, R12, 56);
    e.cmp(A, 1);
    e.0.jump_if(0x84, "pipe-notify-child");
    e.load(R11, R12, HEADER + 16);
    e.rr(0x39, A, R11);
    e.0.jump_if(0x85, "fatal");
    e.mov(R10, R12);
    e.add(R10, HEADER + 80);
    e.mov(Di, R12);
    e.add(Di, HEADER + 104);
    e.0.jump("pipe-notify-waiter");
    e.0.bind("pipe-notify-child")?;
    e.mov(R10, R12);
    e.add(R10, HEADER + 96);
    e.mov(Di, R12);
    e.add(Di, HEADER + 120);
    e.0.bind("pipe-notify-waiter")?;
    e.load(C, R10, 0);
    e.cmp(C, 2);
    e.0.jump_if(0x82, "pipe-notify-return");
    e.cmp(C, 3);
    e.0.jump_if(0x87, "fatal");
    e.load(A, R13, 8);
    e.load(R11, Di, 0);
    e.rr(0x39, A, R11);
    e.0.jump_if(0x85, "pipe-notify-return");
    // The inactive native request and its retained slot must name this exact
    // endpoint generation. A corrupted/matching integer cannot wake another FD.
    e.load(A, R12, CONTEXT + 312);
    e.0.bytes(&[0x89, 0xc0]);
    e.cmp(A, 16);
    e.0.jump_if(0x83, "fatal");
    e.0.bytes(&[0x48, 0xc1, 0xe0, 4]);
    e.mov(Si, R12);
    e.add(Si, 0x3000 + 64);
    e.rr(0x01, Si, A);
    e.load(A, Si, 0);
    e.cmp(A, 1);
    e.0.jump_if(0x82, "fatal");
    e.cmp(A, 32);
    e.0.jump_if(0x87, "fatal");
    e.mov(Si, R12);
    e.add(Si, DESCRIPTIONS);
    e.cmp(A, 16);
    e.0.jump_if(0x86, "pipe-notify-description-base");
    e.add(Si, CHILD_DESCRIPTIONS - DESCRIPTIONS - 16 * 64);
    e.0.bind("pipe-notify-description-base")?;
    e.add(A, -1);
    e.0.bytes(&[0x48, 0xc1, 0xe0, 6]);
    e.rr(0x01, Si, A);
    e.mov(D, C);
    e.add(D, 3);
    e.load(A, Si, 0);
    e.rr(0x39, A, D);
    e.0.jump_if(0x85, "fatal");
    e.load(A, Si, 8);
    e.cmp(A, 0);
    e.0.jump_if(0x84, "fatal");
    e.load(A, Si, 32);
    e.load(R11, Di, 0);
    e.rr(0x39, A, R11);
    e.0.jump_if(0x85, "fatal");
    e.cmp(C, 3);
    e.0.jump_if(0x84, "pipe-notify-writer");
    e.load(A, R13, 40);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "pipe-notify-ready");
    e.load(A, R13, 24);
    e.cmp(A, 0);
    e.0.jump_if(0x84, "pipe-notify-ready");
    e.0.jump("pipe-notify-return");
    e.0.bind("pipe-notify-writer")?;
    e.load(A, R13, 16);
    e.cmp(A, 0);
    e.0.jump_if(0x84, "pipe-notify-ready");
    e.load(D, R12, CONTEXT + 328); // inactive write's original native count
    e.cmp(D, 4096);
    e.0.jump_if(0x86, "pipe-notify-write-size");
    e.imm(D, 1);
    e.0.bind("pipe-notify-write-size")?;
    e.imm(A, 4096);
    e.load(R11, R13, 40);
    e.rr(0x29, A, R11);
    e.rr(0x39, A, D);
    e.0.jump_if(0x82, "pipe-notify-return");
    e.0.bind("pipe-notify-ready")?;
    e.imm(A, 0);
    e.store(R10, 0, A);
    e.store(Di, 0, A);
    e.load(R11, R10, 0);
    e.cmp(R11, 0);
    e.0.jump_if(0x85, "fatal");
    e.load(R11, Di, 0);
    e.cmp(R11, 0);
    e.0.jump_if(0x85, "fatal");
    e.0.bind("pipe-notify-return")?;
    e.0.bytes(&[0xc3]);

    // R13 FIFO; R8 retry syscall, R9 read/write wait kind. No transfer started.
    e.0.bind("pipe-block")?;
    wipe_staging(&mut e);
    e.mov(R15, R12);
    e.load(A, R15, 56);
    e.cmp(A, 1);
    e.0.jump_if(0x84, "pipe-block-parent");
    e.load(R11, R15, HEADER + 16);
    e.rr(0x39, A, R11);
    e.0.jump_if(0x85, "fatal");
    e.imm(C, HEADER as u64 + 96);
    e.imm(D, HEADER as u64 + 120);
    e.imm(Si, HEADER as u64 + 80);
    e.0.jump("pipe-block-record");
    e.0.bind("pipe-block-parent")?;
    e.imm(C, HEADER as u64 + 80);
    e.imm(D, HEADER as u64 + 104);
    e.imm(Si, HEADER as u64 + 96);
    e.0.bind("pipe-block-record")?;
    e.rr(0x01, C, R15);
    e.rr(0x01, D, R15);
    e.rr(0x01, Si, R15);
    e.load(A, C, 0);
    e.cmp(A, 0);
    e.0.jump_if(0x85, "fatal");
    e.store(C, 0, R9);
    e.load(A, R13, 8);
    e.store(D, 0, A);
    e.gs(0x8b, A, 296);
    e.cmp(A, 0x401002);
    e.0.jump_if(0x82, "fatal");
    e.cmp(A, 0x58c285);
    e.0.jump_if(0x83, "fatal");
    e.add(A, -2);
    e.gs(0x89, A, 296);
    e.load(A, R15, HEADER);
    e.cmp(A, 1);
    e.0.jump_if(0x85, "pipe-no-eligible-process");
    e.load(A, Si, 0);
    e.cmp(A, 0);
    e.0.jump_if(0x84, "pair-switch");
    e.0.bind("pipe-no-eligible-process")?;
    // Closed-profile deadlock retains the owned wait. No event/error is invented.
    e.0.bytes(&[0xf3, 0x90]);
    e.0.jump("pipe-no-eligible-process");
    Ok(())
}
